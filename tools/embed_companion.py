#!/usr/bin/env python3
"""Embed the shipped JSON as recovery defaults, with no second C config."""
import argparse
import json
from pathlib import Path


def input_paths(root):
    catalog = json.loads((root / 'config/companion.json').read_text())
    return [root / 'config/companion.json'] + [
        root / 'config' / core['profile'] for core in catalog['cores']]


def generate(root):
    files = input_paths(root)
    lines = ['/* Generated by tools/embed_companion.py; edit the JSON files in config/. */']
    for i, path in enumerate(files):
        data = json.dumps(json.loads(path.read_text()), ensure_ascii=True, separators=(',', ':'))
        lines.append('static const char companion_default_%d[] =' % i)
        for start in range(0, len(data), 100):
            lines.append('  ' + json.dumps(data[start:start + 100]))
        lines[-1] += ';'
    lines += ['static const char *const companion_defaults[] = {',
              ',\n'.join('  companion_default_%d' % i for i in range(len(files))), '};', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--paths', action='store_true', help='print all JSON build dependencies from the catalog')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    if args.paths:
        print('\n'.join(map(str, input_paths(root))))
        raise SystemExit(0)
    target = root / 'mnano/companion_defaults.h'
    result = generate(root)
    if args.check:
        if not target.exists() or target.read_text() != result:
            raise SystemExit('companion defaults are stale: run python3 tools/embed_companion.py')
    elif not target.exists() or target.read_text() != result:
        target.write_text(result)
